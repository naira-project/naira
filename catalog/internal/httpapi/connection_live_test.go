// TestLiveClusterConnection reads existing lab fixtures; it never creates or imports resources.
// NAIRA_LIVE_KUBECONFIG_DIR must contain kubeconfigs generated by k8s-real-test/lab.sh.
func TestLiveClusterConnection(t *testing.T) {
	directory := os.Getenv("NAIRA_LIVE_KUBECONFIG_DIR")
	if testing.Short() || directory == "" {
		t.Skip("set NAIRA_LIVE_KUBECONFIG_DIR and run without -short for live checks")
	}
	client := fake.NewClientset()
	credentials, err := connectiontest.NewSecretStore(client.CoreV1(), map[string][]string{
		clusterregistry.TestWorkspaceID: {
			"naira/reader#kubeconfig", "naira/no-services#kubeconfig", "naira/no-access#kubeconfig",
		},
	})
	require.NoError(t, err)
	store := clusterregistry.NewMemoryStore()
	service := clusterregistry.NewService(store)
	tester := connectiontest.NewKubernetesTester(credentials)
	connectionTestService := connectiontest.NewService(service, store, tester.Test)
	oidc := oidctest.New(t, "live-cluster")
	router, err := NewRouter(nil, nil, nil, nil, keycloak.Config{Client: gocloak.NewClient(oidc.BaseURL), Realm: "live-cluster", Issuer: oidc.Issuer}, &clusters.Registry{
		Registrations:   service,
		ConnectionTests: connectionTestService,
	})
	require.NoError(t, err)
	server := httptest.NewServer(router)
	defer server.Close()
	token := oidc.SignAccessToken(t, "operator")
	for _, profile := range []string{"reader", "no-services", "no-access"} {
		t.Run(profile, func(t *testing.T) {
			path := filepath.Join(directory, profile+".host.kubeconfig")
			data, err := os.ReadFile(path)
			require.NoError(t, err)
			_, err = client.CoreV1().Secrets("naira").Create(t.Context(), &corev1.Secret{
				ObjectMeta: metav1.ObjectMeta{Name: profile},
				Data:       map[string][]byte{"kubeconfig": data},
			}, metav1.CreateOptions{})
			require.NoError(t, err)
			var config struct {
				Clusters []struct {
					Cluster struct {
						Server string `json:"server"`
					} `json:"cluster"`
				} `json:"clusters"`
				Context string `json:"current-context"`
			}
			require.NoError(t, json.Unmarshal(data, &config))
			require.Len(t, config.Clusters, 1)
			cluster, err := service.Create(t.Context(), clusterregistry.Caller{Issuer: oidc.Issuer, Subject: "operator"}, clusterregistry.CreateParams{
				Name: profile, Workspace: clusterregistry.Workspace{ID: clusterregistry.TestWorkspaceID}, CredentialRef: "kubernetes-secret:naira/" + profile + "#kubeconfig",
				Kubernetes: clusterregistry.KubernetesConnection{APIEndpoint: config.Clusters[0].Cluster.Server, Context: config.Context},
			})
			require.NoError(t, err)
			req, err := http.NewRequestWithContext(t.Context(), http.MethodPost, server.URL+"/v1/workspaces/test-workspace/registrations/"+cluster.ID.String()+":test", nil)
			require.NoError(t, err)
			req.Header.Set("Authorization", "Bearer "+token)
			response, err := server.Client().Do(req)
			require.NoError(t, err)
			defer response.Body.Close()
			require.Equal(t, http.StatusOK, response.StatusCode)
			var result clusterregistry.ValidationResult
			require.NoError(t, json.NewDecoder(response.Body).Decode(&result))
			want := clusterregistry.ValidationFailed
			if profile == "reader" {
				want = clusterregistry.ValidationReady
			}
			assert.Equal(t, want, result.Status)
			for _, check := range result.Checks {
				t.Logf("%s: %s passed=%t", check.Name, check.Code, check.Passed)
			}
			if profile == "no-services" {
				require.Equal(t, "FORBIDDEN", result.Checks[len(result.Checks)-1].Code)
			}
			stored, err := store.Get(t.Context(), cluster.Workspace, cluster.ID)
			require.NoError(t, err)
			assert.Equal(t, result, *stored.LastValidation)
		})
	}
}
